def add_prior_season_rolling(df, group_col, window, output_col):


    history = {}
    result = np.full(len(df), np.nan, dtype=np.float32)

    years = np.sort(df["year"].dropna().unique())
    year_values = df["year"].to_numpy()

    for year in years:
        positions = np.flatnonzero(year_values == year)

        # 1. Calculer les features avant d'ajouter les cibles de l'année.
        for pos in positions:
            key = df.iloc[pos][group_col]

            if pd.isna(key):
                continue

            previous_values = history.get(key, [])

            if previous_values:
                result[pos] = np.mean(previous_values[-window:])

        # 2. Ajouter l'historique seulement pour les saisons d'entraînement.
        # Les cibles des saisons de test ne sont jamais ajoutées.
        if year <= CUTOFF_YEAR:
            for pos in positions:
                key = df.iloc[pos][group_col]

                if pd.isna(key):
                    continue

                value = df.iloc[pos]["milliseconds"]

                if pd.notna(value):
                    history.setdefault(key, []).append(float(value))

    df[output_col] = result
    return df


