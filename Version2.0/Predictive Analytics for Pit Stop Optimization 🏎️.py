def encode_from_history(history_df, current_values, col, alpha=10):


    history_df = history_df.dropna(
        subset=[col, "milliseconds"]
    )

    if history_df.empty:
        return pd.Series(
            np.nan,
            index=current_values.index,
            dtype="float32"
        )

    global_mean = history_df["milliseconds"].mean()

    stats = history_df.groupby(
        col,
        observed=True
    )["milliseconds"].agg(["mean", "count"])

    smoothed = (
        stats["count"] * stats["mean"] + alpha * global_mean
    ) / (
        stats["count"] + alpha
    )

    return (
        current_values.map(smoothed)
        .fillna(global_mean)
        .astype("float32")
    )


